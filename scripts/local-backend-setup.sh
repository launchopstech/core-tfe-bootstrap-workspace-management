#!/usr/bin/env bash
# Generate backend_override.tf files for local CLI-driven runs.
# These files are gitignored (*_override.tf) and do not affect VCS-triggered runs.
#
# Usage:
#   ./scripts/local-backend-setup.sh [organization]
#
# After running this script:
#   TF_WORKSPACE=test-client-dev-rds terraform -chdir=workspaces/rds init
#   TF_WORKSPACE=test-client-dev-rds terraform -chdir=workspaces/rds plan
#   TF_WORKSPACE=test-client-dev-rds terraform -chdir=workspaces/rds apply

set -euo pipefail

ORG="${1:-core-aws}"
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"

ROOTS=(
  "workspaces/rds"
  "workspaces/vpc"
  "workspaces/dns"
  "workspaces/lambda"
  "workspaces/api"
  "workspaces/secure-baseline"
  "workspaces/account-bootstrap"
  "workspaces/account-portal"
  "bootstrap-accounts-varset"
  "bootstrap-accounts-dev"
  "bootstrap-accounts-workbench"
  "hcp-bootstrap"
)

for root in "${ROOTS[@]}"; do
  dir="${REPO_ROOT}/${root}"
  [ -d "$dir" ] || continue

  cat > "${dir}/backend_override.tf" <<EOF
# Auto-generated by scripts/local-backend-setup.sh — do not commit.
# Enables local CLI-driven runs against HCP Terraform.
terraform {
  cloud {
    organization = "${ORG}"
  }
}
EOF

  echo "Created ${root}/backend_override.tf"
done

echo ""
echo "Done. Use TF_WORKSPACE to select a workspace:"
echo "  TF_WORKSPACE=test-client-dev-rds terraform -chdir=workspaces/rds init"
echo "  TF_WORKSPACE=test-client-dev-rds terraform -chdir=workspaces/rds plan"
